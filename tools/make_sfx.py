"""Render the machine's cabinet sound effects (SAC sequences from KLU_SoundResources) for the DS.

Outputs:
  game/data/sfx_<name>.bin   DS IMA-ADPCM (4-byte header + nibbles), mono, SFX_RATE Hz
  game/include/sfx_list.h    enum + table (data pointer, size)
  build/sfx/<name>.wav       16-bit previews of exactly what is encoded
"""
import os, sys, wave
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'extract'))
from paths import DATA as ROOT  # original game data (extract/paths.py)
import movies_audio as ma  # SAC sequence renderer (sacinfo.csv / SD_cache.txt)

OUT = os.path.join(HERE, '..', 'game', 'data')
INC = os.path.join(HERE, '..', 'game', 'include')
PRE = os.path.join(HERE, '..', 'build', 'sfx')
os.makedirs(PRE, exist_ok=True)

SFX_RATE = 32728  # DS-friendly rate (timer = 0x1000000 / 512 cycles)
SFX_PEAK = 0.95   # every effect is normalised to this peak level

# (enum name, SAC sequence, max seconds)
SFX = [
    ('BET', 'SD_SE_sys_cmd_BET_A', 2),
    ('LEVER', 'SD_SE_sys_cmd_LV_A', 3),
    ('STOP', 'SD_SE_sys_cmd_STOP_A', 2),
    ('TENPAI', 'SD_SE_sys_reel_STOP_def_TENPAI_BB', 3),
    ('PAY_REPLAY', 'SD_SE_sys_pay_REPLAY_A', 3),
    ('PAY_BELL', 'SD_SE_sys_pay_BELL_A1', 3),
    ('PAY_SUIKA', 'SD_SE_sys_pay_SUIKA_A', 3),
    ('PAY_CHERRY', 'SD_SE_sys_pay_BELL_B1', 3),
    ('BIG_START', 'SD_JINGLE_A1', 8),
    ('REG_START', 'SD_JINGLE_B1', 8),
    ('BONUS_END', 'SD_JINGLE_D1', 8),
    ('CHANCE', 'SD_SE_sys_CUSTOM_ChanceBtn_PUSH', 2),
    ('UI_START', 'SD_SE_NV_SE_IN_B', 3),     # TAP TO START confirmed
    ('UI_OK', 'SD_SE_NV_SE_OK', 2),          # menu item chosen
    ('UI_BACK', 'SD_SE_NV_SE_NG', 2),        # back to the menu
    ('UI_CURSOR', 'SD_SE_Fc04_SELECT', 2),   # cursor moved with the d-pad
    ('WAIT', 'SD_SE_sys_cmd_WAIT_A', 4.2),   # 4.1 s game wait (WAIT CUT off), cut when the reels start
]

STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80,
        88, 97, 107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598,
        658, 724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327,
        3660, 4026, 4428, 4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289,
        16818, 18500, 20350, 22385, 24623, 27086, 29794, 32767]
IDX = [-1, -1, -1, -1, 2, 4, 6, 8]


def adpcm_encode(pcm):
    """IMA-ADPCM as decoded by the DS sound hardware. Returns (bytes, decoded preview)."""
    pred, index = int(pcm[0]), 0
    out = bytearray(np.int16(pred).tobytes() + bytes([index, 0]))
    dec = np.zeros(len(pcm), np.int16)
    nib = []
    for i, s in enumerate(pcm):
        step = STEP[index]
        diff = int(s) - pred
        code = 0
        if diff < 0:
            code = 8
            diff = -diff
        d = step >> 3
        if diff >= step:
            code |= 4; diff -= step; d += step
        if diff >= step >> 1:
            code |= 2; diff -= step >> 1; d += step >> 1
        if diff >= step >> 2:
            code |= 1; d += step >> 2
        pred = max(-32767, min(32767, pred - d if code & 8 else pred + d))
        index = max(0, min(88, index + IDX[code & 7]))
        nib.append(code)
        dec[i] = pred
    if len(nib) & 1:
        nib.append(0)
    for i in range(0, len(nib), 2):
        out.append(nib[i] | (nib[i + 1] << 4))
    while len(out) & 3:
        out.append(0)
    return bytes(out), dec


# effects kept at their original (quiet) mix level instead of being normalised
KEEP_LEVEL = {'SD_SE_sys_cmd_WAIT_A'}


def render(sac_name, max_s):
    a = ma.render_sac(ma.sac_by_name[sac_name], max_s)
    mono = a.mean(axis=1)
    level = np.abs(mono)
    nz = np.nonzero(level > 0.002)[0]
    mono = mono[:nz[-1] + 1] if len(nz) else mono[:1]
    # 44100 -> SFX_RATE
    n = int(len(mono) * SFX_RATE / ma.RATE)
    x = np.interp(np.arange(n) * ma.RATE / SFX_RATE, np.arange(len(mono)), mono)
    # short fade-out to avoid a click when truncated
    fade = min(len(x), SFX_RATE // 100)
    x[-fade:] *= np.linspace(1, 0, fade)
    # normalise: the cabinet effects must stand out over the video / music
    peak = np.abs(x).max()
    if peak > 0 and sac_name not in KEEP_LEVEL:
        x = x * (SFX_PEAK / peak)
    return np.clip(x * 32767, -32767, 32767).astype(np.int16)


def main():
    total = 0
    with open(os.path.join(INC, 'sfx_list.h'), 'w') as h:
        h.write('// generated by tools/make_sfx.py\n#pragma once\n\n')
        h.write(f'#define SFX_RATE {SFX_RATE}\n\ntypedef enum\n{{\n')
        for name, _, _ in SFX:
            h.write(f'    SFX_{name},\n')
        h.write('    SFX_COUNT\n} sfx_id_t;\n\n#ifdef SFX_IMPLEMENTATION\n')
        for name, _, _ in SFX:
            h.write(f'#include "sfx_{name.lower()}_bin.h"\n')
        h.write('static const struct { const void *data; u32 size; } sfx_table[SFX_COUNT] = {\n')
        for name, _, _ in SFX:
            h.write(f'    {{ sfx_{name.lower()}_bin, sfx_{name.lower()}_bin_size }},\n')
        h.write('};\n#endif\n')
    for name, sac, max_s in SFX:
        pcm = render(sac, max_s)
        data, dec = adpcm_encode(pcm)
        with open(os.path.join(OUT, f'sfx_{name.lower()}.bin'), 'wb') as f:
            f.write(data)
        with wave.open(os.path.join(PRE, f'{name.lower()}.wav'), 'wb') as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(SFX_RATE)
            w.writeframes(dec.tobytes())
        total += len(data)
        print(f'{name:12s} {sac:36s} {len(pcm) / SFX_RATE:5.2f}s {len(data) // 1024:4d} KB')
    print('total', total // 1024, 'KB')


if __name__ == '__main__':
    main()
