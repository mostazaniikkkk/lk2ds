"""Asset pack stored in the ROM's NitroFS (videos excepted: see VIDEOS) (game/nitrofs/lk2ds.pak): data loaded on demand instead of
living in RAM all the time. The listed files are moved out of game/data (so they are no longer
embedded in the ARM9 binary) into game/pak_src, then packed.

Pack format (little endian): u32 magic 'LKPK', u32 count, {u32 offset, u32 size}[count], data
(offsets from the start of the pack, 32-byte aligned). IDs: game/include/pak_ids.h
Run after the other asset tools (they write into game/data).
"""
import os, shutil, struct

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.join(HERE, '..', 'game')
DATA = os.path.join(GAME, 'data')
SRC = os.path.join(GAME, 'pak_src')
OUT = os.path.join(GAME, 'nitrofs')
INC = os.path.join(GAME, 'include')

FILES = [
    'bgm_title.bin', 'bgm_menu.bin', 'bgm_race.bin', 'bgm_ecm.bin', 'bgm_rion.bin', 'bgm_tsug.bin',
    'bgm_art.bin', 'bgm_artsp.bin', 'bgm_zone.bin', 'bgm_ichigo.bin', 'bgm_battle.bin', 'bgm_ashi.bin',
    'bgm_nade.bin', 'bgm_va.bin',
    'splash_top_lz.bin', 'splash_bot_lz.bin', 'caution_top_lz.bin', 'caution_bot_lz.bin',
    'title_top_lz.bin', 'title_bot_lz.bin', 'title_tap.bin', 'title_notap.bin', 'menu_bot_lz.bin',
    'page_terms_lz.bin', 'page_license_lz.bin',
    'settings_bot_lz.bin', 'settings_ctrl.bin', 'settings_desc.bin',
    'guide_bg_lz.bin',
    'opening_bot_lz.bin',  # bottom screen during the opening ("PRESS START TO SKIP")
]
# FastVideoDS clips live outside the ROM, as files in data/lk2ds/movies/ on the SD card (like an Android app's external data):
# they are most of the size, and streaming them from their own files is what FastVideoDS is made for.
# Copied to build/sd/data/lk2ds/movies/<name>.fv; ids and names in game/include/video_ids.h.
VIDEOS = [
    'video_opening.bin',   # boot opening = BIG clip over "Resonation Wings", Sn_Dd01_0001 (tools/make_opening.py)
    # normal-mode idle screen, one clip per background, chained by the game (tools/make_idle.py --split)
    'video_idle_0.bin', 'video_idle_1.bin', 'video_idle_2.bin', 'video_idle_3.bin', 'video_idle_4.bin',
    'video_idle_5.bin', 'video_idle_6.bin',
]
# continuous effect clips, listed by tools/make_effects.py in the order the game indexes them
_FX_LIST = os.path.join(HERE, 'effect_files.txt')
if os.path.exists(_FX_LIST):
    VIDEOS += [l.strip() for l in open(_FX_LIST) if l.strip()]
# the machine's songs (tools/make_songs.py)
_SONGS = os.path.join(HERE, 'song_list.txt')
if os.path.exists(_SONGS):
    VIDEOS += [f'song_{int(l.split(chr(9))[0]):02d}.bin' for l in open(_SONGS, encoding='utf8') if l.strip()]
MOVIES = os.path.join(HERE, '..', 'build', 'sd', 'data', 'lk2ds', 'movies')


def video_name(f):
    """SD file name of a clip: video_idle.bin -> idle.fv, fx_race_intro.bin -> race_intro.fv"""
    n = f[:-4]
    for p in ('video_', 'fx_'):
        if n.startswith(p):
            n = n[len(p):]
    return n + '.fv'


def export_videos():
    os.makedirs(MOVIES, exist_ok=True)
    total = 0
    for name in VIDEOS:
        fresh, kept = os.path.join(DATA, name), os.path.join(SRC, name)
        if os.path.exists(fresh):
            shutil.move(fresh, kept)
        dst = os.path.join(MOVIES, video_name(name))
        if not os.path.exists(dst) or os.path.getmtime(dst) < os.path.getmtime(kept):
            shutil.copy2(kept, dst)
        total += os.path.getsize(kept)
    with open(os.path.join(INC, 'video_ids.h'), 'w') as h:
        h.write('// generated by tools/make_pak.py: clips in data/lk2ds/movies/ on the SD card\n#pragma once\n\n')
        h.write('typedef enum\n{\n')
        for name in VIDEOS:
            h.write(f'    VID_{name[:-4].upper().replace("VIDEO_", "")},\n')
        h.write('    VID_COUNT\n} video_id_t;\n\n')
        h.write('static const char *const sVideoFile[VID_COUNT] = {\n')
        for name in VIDEOS:
            h.write(f'    "{video_name(name)}",\n')
        h.write('};\n')
    print(f'{len(VIDEOS)} videos, {total // (1 << 20)} MB -> {os.path.normpath(MOVIES)}')
# gallery pages and previews, listed by tools/make_gallery.py
_GAL_LIST = os.path.join(HERE, 'gallery_files.txt')
if os.path.exists(_GAL_LIST):
    FILES += [l.strip() for l in open(_GAL_LIST) if l.strip()]
# date sim stills, listed by tools/make_date.py
_DATE_LIST = os.path.join(HERE, 'date_files.txt')
if os.path.exists(_DATE_LIST):
    FILES += [l.strip() for l in open(_DATE_LIST) if l.strip()]


def main():
    os.makedirs(SRC, exist_ok=True)
    export_videos()
    os.makedirs(OUT, exist_ok=True)
    blobs = []
    for name in FILES:
        fresh, kept = os.path.join(DATA, name), os.path.join(SRC, name)
        if os.path.exists(fresh):  # newly generated: take it out of the embedded data
            shutil.move(fresh, kept)
        with open(kept, 'rb') as f:
            blobs.append(f.read())
    head = 8 + 8 * len(blobs)
    pos = (head + 31) & ~31
    table, body = [], b''
    for b in blobs:
        table.append((pos, len(b)))
        pad = ((len(b) + 31) & ~31) - len(b)
        body += b + b'\0' * pad
        pos += len(b) + pad
    data = struct.pack('<II', 0x4B504B4C, len(blobs)) + b''.join(struct.pack('<II', *t) for t in table)
    data += b'\0' * (((head + 31) & ~31) - head) + body
    with open(os.path.join(OUT, 'lk2ds.pak'), 'wb') as f:
        f.write(data)
    with open(os.path.join(INC, 'pak_ids.h'), 'w') as h:
        h.write('// generated by tools/make_pak.py\n#pragma once\n\ntypedef enum\n{\n')
        for name in FILES:
            h.write(f'    PAK_{name[:-4].upper()},\n')
        h.write('    PAK_COUNT\n} pak_id_t;\n')
    print(f'{len(blobs)} files, {len(data) // 1024} KB')


if __name__ == '__main__':
    main()
